// Generates src/tokens.css: Material 3 colour roles derived from a seed by the
// official Material Color Utilities, plus the type, shape, elevation and motion
// scales from the M3 spec. Run offline; the app itself ships only static CSS,
// so nothing here is a dependency of the app.
//
//   npm install --no-save @material/material-color-utilities
//   node tools/make-tokens.mjs
//
// Change SEED to re-derive every colour role. The rest of the stylesheet reads
// this file's variables and never a hex value of its own.
import { themeFromSourceColor, argbFromHex, hexFromArgb } from '@material/material-color-utilities';
import fs from 'node:fs';

const SEED = '#a8431f';
const theme = themeFromSourceColor(argbFromHex(SEED));
const P = theme.palettes;
const h = (palette, tone) => hexFromArgb(palette.tone(tone));

const fixed = (p) => ({
  'primary-fixed': h(p, 90),
  'primary-fixed-dim': h(p, 80),
  'on-primary-fixed': h(p, 10),
  'on-primary-fixed-variant': h(p, 30)
});

function scheme(kind) {
  const dark = kind === 'dark';
  const primary = dark ? 80 : 40;
  const onPrimary = dark ? 20 : 100;
  const container = dark ? 30 : 90;
  const onContainer = dark ? 90 : 10;

  return {
    primary: h(P.primary, primary),
    'on-primary': h(P.primary, onPrimary),
    'primary-container': h(P.primary, container),
    'on-primary-container': h(P.primary, onContainer),
    ...fixed(P.primary),

    secondary: h(P.secondary, primary),
    'on-secondary': h(P.secondary, onPrimary),
    'secondary-container': h(P.secondary, container),
    'on-secondary-container': h(P.secondary, onContainer),
    'secondary-fixed': h(P.secondary, 90),
    'secondary-fixed-dim': h(P.secondary, 80),
    'on-secondary-fixed': h(P.secondary, 10),
    'on-secondary-fixed-variant': h(P.secondary, 30),

    tertiary: h(P.tertiary, primary),
    'on-tertiary': h(P.tertiary, onPrimary),
    'tertiary-container': h(P.tertiary, container),
    'on-tertiary-container': h(P.tertiary, onContainer),
    'tertiary-fixed': h(P.tertiary, 90),
    'tertiary-fixed-dim': h(P.tertiary, 80),
    'on-tertiary-fixed': h(P.tertiary, 10),
    'on-tertiary-fixed-variant': h(P.tertiary, 30),

    error: h(P.error, primary),
    'on-error': h(P.error, onPrimary),
    'error-container': h(P.error, container),
    'on-error-container': h(P.error, onContainer),

    // Surface roles: the neutral tonal palette at the tones M3 assigns them.
    surface: h(P.neutral, dark ? 6 : 98),
    'surface-dim': h(P.neutral, dark ? 6 : 87),
    'surface-bright': h(P.neutral, dark ? 24 : 98),
    'surface-container-lowest': h(P.neutral, dark ? 4 : 100),
    'surface-container-low': h(P.neutral, dark ? 10 : 96),
    'surface-container': h(P.neutral, dark ? 12 : 94),
    'surface-container-high': h(P.neutral, dark ? 17 : 92),
    'surface-container-highest': h(P.neutral, dark ? 22 : 90),
    'on-surface': h(P.neutral, dark ? 90 : 10),
    'on-surface-variant': h(P.neutralVariant, dark ? 80 : 30),
    'outline': h(P.neutralVariant, dark ? 60 : 50),
    'outline-variant': h(P.neutralVariant, dark ? 30 : 80),
    'inverse-surface': h(P.neutral, dark ? 90 : 20),
    'inverse-on-surface': h(P.neutral, dark ? 20 : 95),
    'inverse-primary': h(P.primary, dark ? 40 : 80),
    'surface-tint': h(P.primary, dark ? 80 : 40),
    'shadow': h(P.neutral, 0),
    'scrim': h(P.neutral, 0)
  };
}

const cssRoles = (roles) => Object.entries(roles)
  .map(([name, value]) => `  --md-sys-color-${name}: ${value};`)
  .join('\n');

const typescale = {
  'display-large': [57, 64, 400, '-0.25px'],
  'display-medium': [45, 52, 400, '0'],
  'display-small': [36, 44, 400, '0'],
  'headline-large': [32, 40, 400, '0'],
  'headline-medium': [28, 36, 400, '0'],
  'headline-small': [24, 32, 400, '0'],
  'title-large': [22, 28, 400, '0'],
  'title-medium': [16, 24, 500, '0.15px'],
  'title-small': [14, 20, 500, '0.1px'],
  'body-large': [16, 24, 400, '0.5px'],
  'body-medium': [14, 20, 400, '0.25px'],
  'body-small': [12, 16, 400, '0.4px'],
  'label-large': [14, 20, 500, '0.1px'],
  'label-medium': [12, 16, 500, '0.5px'],
  'label-small': [11, 16, 500, '0.5px']
};

const cssType = Object.entries(typescale).map(([name, [size, line, weight, track]]) =>
  `  --md-sys-typescale-${name}-size: ${size}px;\n` +
  `  --md-sys-typescale-${name}-line-height: ${line}px;\n` +
  `  --md-sys-typescale-${name}-weight: ${weight};\n` +
  `  --md-sys-typescale-${name}-tracking: ${track};`
).join('\n');

const css = `/* GENERATED by tools/make-tokens.mjs from the seed ${SEED}.
   Do not edit by hand: change the seed or the scales and regenerate.
   Colour roles come from the official Material Color Utilities tonal palettes. */

:root {
  color-scheme: light;

  /* --- colour roles, light ------------------------------------------------ */
${cssRoles(scheme('light'))}

  /* --- type: the M3 scale, fifteen named styles -------------------------- */
${cssType}
  --md-ref-typeface-brand: Roboto, "Helvetica Neue", Arial, sans-serif;
  --md-ref-typeface-plain: Roboto, "Helvetica Neue", Arial, sans-serif;

  /* --- shape -------------------------------------------------------------- */
  --md-sys-shape-none: 0px;
  --md-sys-shape-xs: 4px;
  --md-sys-shape-sm: 8px;
  --md-sys-shape-md: 12px;
  --md-sys-shape-lg: 16px;
  --md-sys-shape-xl: 28px;
  --md-sys-shape-full: 9999px;

  /* --- elevation ---------------------------------------------------------- */
  --md-sys-elevation-0: none;
  --md-sys-elevation-1: 0 1px 2px rgba(0, 0, 0, 0.3), 0 1px 3px 1px rgba(0, 0, 0, 0.15);
  --md-sys-elevation-2: 0 1px 2px rgba(0, 0, 0, 0.3), 0 2px 6px 2px rgba(0, 0, 0, 0.15);
  --md-sys-elevation-3: 0 1px 3px rgba(0, 0, 0, 0.3), 0 4px 8px 3px rgba(0, 0, 0, 0.15);
  --md-sys-elevation-4: 0 2px 3px rgba(0, 0, 0, 0.3), 0 6px 10px 4px rgba(0, 0, 0, 0.15);
  --md-sys-elevation-5: 0 4px 4px rgba(0, 0, 0, 0.3), 0 8px 12px 6px rgba(0, 0, 0, 0.15);

  /* --- state layers: the M3 overlay opacities ----------------------------- */
  --md-sys-state-hover: 0.08;
  --md-sys-state-focus: 0.10;
  --md-sys-state-pressed: 0.10;
  --md-sys-state-dragged: 0.16;

  /* --- motion ------------------------------------------------------------- */
  --md-sys-motion-easing-standard: cubic-bezier(0.2, 0, 0, 1);
  --md-sys-motion-easing-standard-decelerate: cubic-bezier(0, 0, 0, 1);
  --md-sys-motion-easing-standard-accelerate: cubic-bezier(0.3, 0, 1, 1);
  --md-sys-motion-easing-emphasized: cubic-bezier(0.2, 0, 0, 1);
  --md-sys-motion-easing-emphasized-decelerate: cubic-bezier(0.05, 0.7, 0.1, 1);
  --md-sys-motion-easing-emphasized-accelerate: cubic-bezier(0.3, 0, 0.8, 0.15);
  --md-sys-motion-duration-short2: 100ms;
  --md-sys-motion-duration-short4: 200ms;
  --md-sys-motion-duration-medium2: 300ms;
  --md-sys-motion-duration-long2: 500ms;
}

@media (prefers-color-scheme: dark) {
  :root {
    color-scheme: dark;

    /* --- colour roles, dark ----------------------------------------------- */
${cssRoles(scheme('dark'))}
  }
}
`;

fs.writeFileSync(new URL('../src/tokens.css', import.meta.url), css);
console.log('wrote src/tokens.css');
console.log('light primary  ', scheme('light').primary);
console.log('light surface  ', scheme('light').surface);
console.log('dark surface   ', scheme('dark').surface);
console.log('dark on-surface', scheme('dark')['on-surface']);
